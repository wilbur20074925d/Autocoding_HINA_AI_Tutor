export const messages: Record<AppLanguage, Record<MessageKey, string>> = {
  en,
  'zh-CN': zhCN,
  'zh-TW': zhTW,
};

export function normalizeAppLanguage(code: string | null | undefined): AppLanguage {
  if (!code) return 'en';
  if (code === 'zh-TW' || code === 'zh-HK') return 'zh-TW';
  if (code.toLowerCase().startsWith('zh')) return 'zh-CN';
  return 'en';
}

export function readAppLanguage(): AppLanguage {
  if (typeof window === 'undefined') return 'en';
  const stored = window.localStorage.getItem('lang');
  if (stored) return normalizeAppLanguage(stored);
  return normalizeAppLanguage(window.navigator.language);
}

export function translate(
  language: AppLanguage,
  key: MessageKey,
  vars?: Record<string, string>
): string {
  const template = messages[language][key] ?? messages.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => vars[name] ?? '');
}
